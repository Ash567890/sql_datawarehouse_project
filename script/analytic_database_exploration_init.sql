use datawarehouse;
go

select * from INFORMATION_SCHEMA.TABLES;

select * from INFORMATION_SCHEMA.COLUMNS
where TABLE_NAME = 'dim_product';

select * from gold.dim_customer;

--Find the date of first and last order

select * from gold.fact_sales;

select 
MIN(order_date) first_order,
MAX(order_date) last_order,
DATEDIFF(year, MIN(order_date), MAX(order_date)) order_range_years
from gold.fact_sales;

--Find the youngest and oldest customer

select 
MIN(birthdate) oldest_customer,
MAX(birthdate) younest_customer,
DATEDIFF(year, MIN(birthdate), GETDATE()),
DATEDIFF(year, MAX(birthdate), GETDATE())
from gold.dim_customer;

-- Find the total sales 

select 
SUM(sales) as total_sales
from gold.fact_sales

-- Find how many items are sold

select 
SUM(quantity) AS total_quantity
from gold.fact_sales;

-- Find the average selling price

select 
AVG(sales) AS avg_sales
from gold.fact_sales;

-- Total the number of order 

select 
COUNT(distinct order_number)
from gold.fact_sales;

-- Total the total number of products 

select 
COUNT(distinct product_name)
from gold.dim_product;

-- Find the total number of customers

select 
count(distinct customer_id)
from gold.dim_customer;

-- Find the total number of customers who have placed an order

select 
count(distinct d.customer_key)
from gold.fact_sales f
left join gold.dim_customer d
on f.customer_key = d.customer_key

/*
Generate key metrics for reporting 
*/
select 
'Total Sales' metrics_for_report,
SUM(sales) as total_sales
from gold.fact_sales

union all

select 
'Total Quantity',
SUM(quantity) total_quantity
from gold.fact_sales

union all

select
'Average Sales',
AVG(sales) as avg_sales
from gold.fact_sales

union all

select 
'Total orders',
COUNT(distinct order_number)
from gold.fact_sales

union all

select 
'Total Product',
COUNT(distinct product_name)
from gold.dim_product;

